def pick(seed, opts, n=1):
    h = int(hashlib.md5(seed.encode()).hexdigest(), 16)
    pool=list(opts); out=[]
    for i in range(min(n,len(pool))):
        idx=(h+i*19)%len(pool); out.append(pool.pop(idx))
    return out

