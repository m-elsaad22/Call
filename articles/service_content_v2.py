def _faq_block(items: list[tuple[str, str]]) -> str:
    parts = ['<h2>أسئلة شائعة</h2>']
    for q, a in items:
        parts.append(f"<h3>{q}</h3>\n<p>{a}</p>")
    parts.append("[post_call]")
    return "\n\n".join(parts)


