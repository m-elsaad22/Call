def classify(title: str, service: str) -> str:
    blob = f"{title} {service}"
    rules = [
        ("landscaping", ["نخيل", "أشجار", "حدائق", "عشب", "ري", "نوافير", "شلالات", "برجولات", "ظلال", "مظلات", "عرائش", "تنسيق"]),
        ("pest", ["مكافحة", "حشرات", "رمة", "وزغ", "صراصير", "أفاعي", "بق", "فئران", "براغيث", "بعوض", "عقارب", "طيور"]),
        ("insulation", ["عزل", "رطوبة", "تبطين", "عفن"]),
        ("cleaning", ["تنظيف", "غسيل", "بيارات", "شفط"]),
        ("moving", ["نقل", "تخزين"]),
        ("renovation", ["ترميم", "تشقق", "فحص فلل", "منازل قديمة"]),
        ("repair", ["صيانة", "إصلاح", "غسالات", "أفران", "ثلاج", "ميكروويف", "مصعد", "أوتومات", "كاميرات", "شفاطات", "مضخات", "مبردات", "بوتاجاز", "مسابح"]),
        ("install", ["تركيب", "جبس", "حجر", "فينيل", "بلاستر", "طاقة", "أبواب", "شبابيك", "انترلوك", "طابوق", "سجاد", "أسقف", "مطابخ"]),
        ("trades", ["نجار", "حداد", "سباك"]),
    ]
    for name, keys in rules:
        if any(k in blob for k in keys):
            return name
    return "general"


def _pick(seed: str, options: list[str], n: int = 1) -> list[str]:
    h = int(hashlib.md5(seed.encode("utf-8")).hexdigest(), 16)
    out = []
    pool = list(options)
    for i in range(min(n, len(pool))):
        idx = (h + i * 17) % len(pool)
        out.append(pool.pop(idx))
    return out


def _short_service(service: str, keyword: str) -> str:
    """Human label without forcing full company title everywhere."""
    s = service.replace("شركة ", "").strip()
    if len(s) < 4:
        s = keyword.replace("شركة ", "").strip()
    # drop trailing city if present
    s = re.sub(r"\s+في\s+.+$", "", s).strip()
    return s or keyword


def build_article_v2(ctx: dict, media: list[dict], helpers: dict) -> str:
    fa = helpers["fa"]
    mobile_table = helpers["mobile_table"]
    callout = helpers["callout"]
    img_tag = helpers["img_tag"]
    areas_for = helpers["areas_for"]
    ensure_kw_density = helpers["ensure_kw_density"]
    word_count = helpers["word_count"]
    WP = helpers["WP"]
    PHONE = helpers["PHONE"]

    kw = ctx["keyword"]
    city = ctx["city"]
    service = ctx["service"]
    short = _short_service(service, kw)
    cat = classify(kw, service)
    areas = areas_for(city)
    a1, a2, a3, a4 = (areas + ["وسط المدينة"] * 4)[:4]
    seed = f"{kw}|{city}|{cat}"

    m0 = media[0] if media else None
    m1 = media[1] if len(media) > 1 else m0
    m2 = media[2] if len(media) > 2 else m0
    m3 = media[3] if len(media) > 3 else m0

    def im(m, alt, eager=False):
        if not m:
            return ""
        return img_tag(m["id"], m["url"], alt, eager=eager)

    schema_img = m0["url"] if m0 else f"{WP}/wp-content/uploads/logo.webp"
    builder = CATEGORY_BUILDERS.get(cat, build_general)
    body = builder(
        kw=kw,
        short=short,
        city=city,
        a1=a1,
        a2=a2,
        a3=a3,
        a4=a4,
        seed=seed,
        im=im,
        m0=m0,
        m1=m1,
        m2=m2,
        m3=m3,
        fa=fa,
        mobile_table=mobile_table,
        callout=callout,
        schema_img=schema_img,
        WP=WP,
        PHONE=PHONE,
    )

    # Enrich with category-specific unique sections (no duplicate pads)
    try:
        from service_content_expand import EXTRAS
        extra_fn = EXTRAS.get(cat)
        parts = []
        if extra_fn:
            parts.append(extra_fn(kw, short, city, a1, a2, a3, a4, seed, callout, mobile_table))
        from service_content_expand import length_boost
        parts.append(length_boost(kw, short, city, a1, a2, a3, a4, seed, cat))
        if parts and "<h2>أسئلة شائعة</h2>" in body:
            body = body.replace("<h2>أسئلة شائعة</h2>", "\n".join(parts) + "\n<h2>أسئلة شائعة</h2>", 1)
    except Exception:
        pass

    # Light natural density only — no spam pads
    body = ensure_kw_density(body, kw, 0.95)
    # Hard strip accidental duplicated consecutive identical paragraphs
    body = re.sub(r"(<p>.*?</p>)(?:\s*\1){1,}", r"\1", body, flags=re.S)
    return body


